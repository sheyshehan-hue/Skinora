# AI growth layer (AI search, smart suggestions, stock and pricing helper) for the static Skinora site.
# Also writes the product catalogue the /api/search function reads. Idempotent.
#   python3 build.py <site dir> <api dir>
import glob, json, os, re, sys
D, API = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
TAG = ('<style id="sk-ai-css">' + open(os.path.join(HERE, 'aigrowth.css')).read() + '</style>'
       '<script id="sk-ai-js">' + open(os.path.join(HERE, 'aigrowth.js')).read() + '</script>')
n = 0
for f in glob.glob(os.path.join(D, '*.html')):
    s = open(f).read()
    if '<script id="sk-feat-data"' not in s: continue
    s = re.sub(r'<style id="sk-ai-css">.*?</style><script id="sk-ai-js">.*?</script>', '', s, flags=re.S)
    s = s.replace('<script id="sk-feat-data"', TAG + '<script id="sk-feat-data"', 1)
    open(f, 'w').write(s); n += 1

home = open(os.path.join(D, 'home.html')).read()
data = json.loads(re.search(r'<script id="sk-data" type="application/json">(.*?)</script>', home, re.S).group(1))
feat = json.loads(re.search(r'<script id="sk-feat-data" type="application/json">(.*?)</script>', home, re.S).group(1))
cat = [{
    'slug': p['slug'], 'brand': p['brand'], 'name': p['name'], 'tagline': p.get('tagline', ''), 'cats': p['cats'], 'gender': p.get('gender'),
    'skin': p['skin'], 'concerns': p['concerns'], 'ingredients': p['ingredients'], 'luxury': p['isLuxury'],
    'sizes': [{'size': v['name'], 'price': v['price'], 'inStock': v['stock'] > 0} for v in p['variants']],
    'rating': round(p['rating'], 1), 'reviews': p['ratingCount'],
    'fragranceFree': any(p['slug'].startswith(x) for x in feat.get('ff', [])),
    'scent': (lambda s: {'family': s[0], 'smellsLike': s[1], 'moods': s[2], 'when': s[3], 'notes': s[5]} if s else None)(feat.get('scents', {}).get(p['slug'])),
} for p in data['products']]
open(os.path.join(API, '_catalog.mjs'), 'w').write('// Generated by layers/aigrowth/build.py from the site data. Do not edit.\nexport default ' + json.dumps(cat, ensure_ascii=False) + ';\n')
print('aigrowth layer applied to %d pages, catalogue of %d products' % (n, len(cat)))
